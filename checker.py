#!/usr/bin/env python3
"""
ai-disclosure-checker — EU AI Act transparency-compliance heuristic scanner.

Scans a website you own (or have explicit permission to scan) for common
AI-disclosure gaps:
  DC-001  Chatbot widget detected with no nearby AI-identification text
  DC-002  Privacy/terms page has no AI-disclosure section (or no such page found)
  DC-003  AI-generated imagery (alt/src markers) without caption disclosure
  DC-004  "Powered by AI" marketing claims with no link to a disclosure page
  DC-005  No machine-readable AI disclosure (disclosure.json / llms.txt AI section)

Every finding is labeled HEURISTIC. This tool is NOT legal advice and does not
prove EU AI Act compliance or non-compliance. For legal certainty, consult counsel.

Stdlib only. Polite crawling: 1 request/second, robots.txt respected,
30s timeout, 2 MB body cap, max 25 pages per scan.
"""

import argparse
import html.parser
import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import urllib.robotparser
import xml.etree.ElementTree as ET

VERSION = "1.0.0"
USER_AGENT = (
    "AIDisclosureChecker/1.0 (+https://disclosure-guard.onrender.com; "
    "polite scan, 1 req/sec)"
)
TIMEOUT = 30
BODY_CAP = 2 * 1024 * 1024
MAX_PAGES = 25
REQUEST_DELAY = 1.0
EVIDENCE_LEN = 160

HEURISTIC_NOTE = (
    "HEURISTIC — pattern-based signal, not legal proof. "
    "Consult counsel for EU AI Act compliance."
)

# ---------------------------------------------------------------------------
# Heuristic data
# ---------------------------------------------------------------------------

CHATBOT_MARKERS = [
    (r"widget\.intercom\.io|intercomSettings|Intercom\(", "Intercom"),
    (r"js\.drift\.com|drift\.load|driftt\.com", "Drift"),
    (r"embed\.hubspot\.com|HubSpotConversations", "HubSpot chat"),
    (r"client\.crisp\.chat|CRISP_WEBSITE_ID", "Crisp"),
    (r"embed\.tawk\.to|Tawk_API", "Tawk.to"),
    (r"code\.tidio\.co|\btidio\b", "Tidio"),
    (r"static\.zendesk\.com|webWidget|zE\s*\(", "Zendesk chat"),
    (r"cdn\.livechatinc\.com|LiveChatWidget|__lc\s*=", "LiveChat"),
    (r"w\.freshchat\.com|fcWidget", "Freshchat"),
    (r"chat-widget|chatbot-widget|ai-chat", "generic chat widget"),
]

AI_IDENTIFICATION_PHRASES = [
    "ai assistant", "ai chatbot", "ai-powered assistant", "virtual assistant",
    "automated assistant", "chatbot", "artificial intelligence", "ai agent",
    "bot", "powered by ai",
]

AI_DISCLOSURE_KEYWORDS = [
    "ai act", "artificial intelligence", "ai-generated", "ai generated",
    "automated decision", "chatbot", "machine-generated", "synthetic content",
    "transparency", "deepfake",
]

AI_IMAGE_MARKERS = [
    "midjourney", "dall-e", "dalle", "stable diffusion", "stablediffusion",
    "ai-generated", "ai generated", "generated by ai", "firefly",
    "leonardo", "ideogram", "nightcafe",
]

IMAGE_DISCLOSURE_PHRASES = [
    "ai-generated", "ai generated", "generated by ai", "created with ai",
    "created by ai", "artificial intelligence", "synthetic image",
    "made with ai",
]

AI_CLAIM_PHRASES = [
    "powered by ai", "ai-powered", "built with ai", "ai-driven",
]

DISCLOSURE_PAGE_HINTS = [
    "privacy", "terms", "disclosure", "legal", "ai-policy", "transparency",
    "cookie",
]


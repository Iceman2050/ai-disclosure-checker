def fetch(url, timeout=TIMEOUT):
    """Fetch a URL. Returns (final_url, body_text or None, status)."""
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            status = getattr(resp, "status", 200) or 200
            raw = resp.read(BODY_CAP + 1)
            if len(raw) > BODY_CAP:
                raw = raw[:BODY_CAP]
            ctype = resp.headers.get("Content-Type", "")
            m = re.search(r"charset=([\w-]+)", ctype, re.IGNORECASE)
            charset = m.group(1) if m else "utf-8"
            try:
                body = raw.decode(charset, errors="replace")
            except (LookupError, ValueError):
                body = raw.decode("utf-8", errors="replace")
            return resp.geturl(), body, status
    except urllib.error.HTTPError as e:
        return url, None, e.code
    except Exception:
        return url, None, 0


def load_robots(base_url):
    rp = urllib.robotparser.RobotFileParser()
    robots_url = urllib.parse.urljoin(base_url, "/robots.txt")
    try:
        rp.set_url(robots_url)
        rp.read()
    except Exception:
        pass
    return rp


def same_origin(a, b):
    pa, pb = urllib.parse.urlparse(a), urllib.parse.urlparse(b)
    return (pa.scheme, pa.netloc) == (pb.scheme, pb.netloc)


def parse_sitemap(sitemap_url, origin):
    urls = []
    _, body, status = fetch(sitemap_url)
    if not body or status != 200:
        return urls
    try:
        root = ET.fromstring(body)
    except ET.ParseError:
        return urls
    tag = root.tag.lower()
    if "sitemapindex" in tag:
        for loc in root.iter():
            if loc.tag.lower().endswith("loc") and loc.text:
                urls.extend(parse_sitemap(loc.text.strip(), origin))
    else:
        for loc in root.iter():
            if loc.tag.lower().endswith("loc") and loc.text:
                u = loc.text.strip()
                if same_origin(u, origin):
                    urls.append(u)
    return urls


def _allowed(rp, url):
    return rp is None or rp.can_fetch(USER_AGENT, url)


def crawl(target, use_sitemap, max_pages, verbose=False):
    """Return list of {'url', 'html'} dicts, politely crawled."""
    pages = []
    seen = set()
    # robots.txt only applies to http(s); file:// and friends skip it
    rp = load_robots(target) if target.startswith(("http://", "https://")) else None
    if not _allowed(rp, target):
        print("robots.txt disallows scanning %s — aborting." % target, file=sys.stderr)
        return pages

    candidates = []
    if use_sitemap:
        sm = urllib.parse.urljoin(target, "/sitemap.xml")
        candidates = parse_sitemap(sm, target)
        if verbose:
            print("sitemap: %d same-origin urls" % len(candidates), file=sys.stderr)
    if not candidates:
        candidates = [target]

    queue = list(dict.fromkeys(candidates))  # de-dupe, keep order
    first = True
    while queue and len(pages) < max_pages:
        url = queue.pop(0)
        if url in seen or not same_origin(url, target):
            continue
        seen.add(url)
        if not _allowed(rp, url):
            continue
        if not first:
            time.sleep(REQUEST_DELAY)
        first = False
        final_url, body, status = fetch(url)
        if verbose:
            print("  [%d] %s" % (status, final_url), file=sys.stderr)
        if body is None or status != 200:
            continue
        ctype_ok = True  # file:// has no content-type; accept and parse anyway
        pages.append({"url": final_url, "html": body})
        if not use_sitemap and len(pages) == 1:
            # BFS one level from homepage links (same origin only)
            for link in sorted(extract_links(body, final_url)):
                if link not in seen and same_origin(link, target):
                    queue.append(link)

    # Ensure common policy pages are included if discoverable by convention
    for hint in ("/privacy", "/terms"):
        guess = urllib.parse.urljoin(target, hint)
        if len(pages) < max_pages and guess not in seen and same_origin(guess, target):
            if _allowed(rp, guess):
                time.sleep(REQUEST_DELAY)
                final_url, body, status = fetch(guess)
                if body and status == 200:
                    pages.append({"url": final_url, "html": body})
    return pages



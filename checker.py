class _TextExtractor(html.parser.HTMLParser):
    """Extract visible text, skipping script/style/noscript."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts = []
        self._skip = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style", "noscript"):
            self._skip += 1
        if tag in ("p", "div", "h1", "h2", "h3", "h4", "li", "tr", "br", "section"):
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in ("script", "style", "noscript") and self._skip:
            self._skip -= 1

    def handle_data(self, data):
        if not self._skip:
            self.parts.append(data)

    def text(self):
        return re.sub(r"[ \t\r\f\v]+", " ", "".join(self.parts))


def extract_text(html):
    ext = _TextExtractor()
    try:
        ext.feed(html)
    except Exception:
        pass
    return ext.text()


def extract_links(html, base_url):
    links = set()
    for m in re.finditer(
        r'<a\s[^>]*?href\s*=\s*["\']([^"\']+)["\']', html, re.IGNORECASE
    ):
        href = m.group(1).strip()
        if href.startswith(("#", "mailto:", "tel:", "javascript:")):
            continue
        links.add(urllib.parse.urljoin(base_url, href))
    return links


def extract_images(html):
    """Return list of dicts: src, alt, and tag position for context windows."""
    images = []
    for m in re.finditer(r"<img\b[^>]*>", html, re.IGNORECASE):
        tag = m.group(0)
        src = re.search(r'src\s*=\s*["\']([^"\']+)["\']', tag, re.IGNORECASE)
        alt = re.search(r'alt\s*=\s*["\']([^"\']*)["\']', tag, re.IGNORECASE)
        images.append(
            {
                "src": src.group(1) if src else "",
                "alt": alt.group(1) if alt else "",
                "start": m.start(),
                "end": m.end(),
            }
        )
    return images


def evidence(text, match_start, match_end, length=EVIDENCE_LEN):
    half = length // 2
    s = max(0, match_start - half)
    e = min(len(text), match_end + half)
    snippet = re.sub(r"\s+", " ", text[s:e]).strip()
    return snippet[:length]


def contains_any(haystack, phrases):
    hay = haystack.lower()
    return any(p in hay for p in phrases)



# Scan orchestration
# ---------------------------------------------------------------------------


def run_checks(pages, target, verbose=False):
    findings = []
    findings.extend(check_chatbot(pages))
    findings.extend(check_policy_disclosure(pages))
    findings.extend(check_ai_images(pages))
    findings.extend(check_ai_claims(pages))
    time.sleep(REQUEST_DELAY)
    findings.extend(check_machine_readable(target))
    return findings


def scan(target, use_sitemap=False, max_pages=MAX_PAGES, verbose=False):
    if not re.match(r"^(https?|file)://", target):
        target = "http://" + target
    pages = crawl(target, use_sitemap, max_pages, verbose=verbose)
    findings = run_checks(pages, target, verbose=verbose) if pages else []
    return {
        "tool": "ai-disclosure-checker",
        "version": VERSION,
        "target": target,
        "pages_scanned": len(pages),
        "findings": findings,
        "note": HEURISTIC_NOTE,
    }


def print_report(report):
    print("=" * 70)
    print("ai-disclosure-checker v%s — %s" % (report["version"], report["target"]))
    print("pages scanned: %d" % report["pages_scanned"])
    print("=" * 70)
    if not report["findings"]:
        print("No disclosure gaps detected. (Heuristic scan — not legal proof.)")
    for f in report["findings"]:
        print("\n[%s] %s — %s" % (f["id"], f["severity"], f["title"]))
        print("  page:     %s" % f["page"])
        print("  evidence: %s" % f["evidence"])
        print("  fix:      %s" % f["fix"])
        print("  note:     HEURISTIC")
    print("\n" + report["note"])


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Heuristic EU AI Act disclosure-gap scanner (not legal advice)."
    )
    ap.add_argument("target", help="Site to scan, e.g. https://example.com")
    ap.add_argument(
        "--sitemap",
        action="store_true",
        help="Discover pages via /sitemap.xml instead of link crawl",
    )
    ap.add_argument(
        "--max-pages", type=int, default=MAX_PAGES, help="Max pages to scan (default 25)"
    )
    ap.add_argument("--json", action="store_true", help="Machine-readable JSON output")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args(argv)

    print(
        "NOTICE: only scan websites you own or have explicit permission to test. "
        "Unauthorized scanning may violate terms of service or law.",
        file=sys.stderr,
    )
    report = scan(args.target, use_sitemap=args.sitemap, max_pages=args.max_pages,
                  verbose=args.verbose)
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print_report(report)
    return 1 if report["findings"] else 0


if __name__ == "__main__":
    sys.exit(main())

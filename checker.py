def check_chatbot(pages):
    findings = []
    for page in pages:
        html, url = page["html"], page["url"]
        detected = []
        for pattern, name in CHATBOT_MARKERS:
            for m in re.finditer(pattern, html, re.IGNORECASE):
                window = html[max(0, m.start() - 3000): m.end() + 3000]
                window_text = extract_text(window)
                if not contains_any(window_text, AI_IDENTIFICATION_PHRASES):
                    detected.append((name, evidence(html, m.start(), m.end())))
                    break
        if detected:
            names = ", ".join(sorted({n for n, _ in detected}))
            findings.append(
                {
                    "id": "DC-001",
                    "severity": "HIGH",
                    "page": url,
                    "title": "Chatbot widget without nearby AI identification",
                    "evidence": "%s :: %s" % (names, detected[0][1]),
                    "fix": (
                        "Add visible text near the widget such as "
                        "'You're chatting with our AI assistant' — the EU AI Act "
                        "requires users to know they are interacting with AI."
                    ),
                    "heuristic": True,
                }
            )
    return findings


def _is_policy_page(url):
    path = urllib.parse.urlparse(url).path.lower()
    return any(h in path for h in DISCLOSURE_PAGE_HINTS)


def check_policy_disclosure(pages):
    findings = []
    policy_pages = [p for p in pages if _is_policy_page(p["url"])]
    if not policy_pages:
        return [
            {
                "id": "DC-002",
                "severity": "MEDIUM",
                "page": pages[0]["url"] if pages else "",
                "title": "No privacy/terms/disclosure page found",
                "evidence": "crawled %d page(s); none matched privacy/terms/disclosure paths"
                % len(pages),
                "fix": (
                    "Publish a privacy policy and add an 'AI & automated "
                    "decision-making' section describing your AI features."
                ),
                "heuristic": True,
            }
        ]
    for page in policy_pages:
        text = extract_text(page["html"])
        if not contains_any(text, AI_DISCLOSURE_KEYWORDS):
            findings.append(
                {
                    "id": "DC-002",
                    "severity": "MEDIUM",
                    "page": page["url"],
                    "title": "Policy page has no AI-disclosure section",
                    "evidence": evidence(text, 0, min(200, len(text))),
                    "fix": (
                        "Add an AI section to %s covering: which AI features "
                        "exist, what data they use, and user rights. Keywords "
                        "the check looks for: %s."
                        % (
                            urllib.parse.urlparse(page["url"]).path,
                            ", ".join(AI_DISCLOSURE_KEYWORDS[:5]),
                        )
                    ),
                    "heuristic": True,
                }
            )
    return findings


def check_ai_images(pages):
    findings = []
    for page in pages:
        html, url = page["html"], page["url"]
        for img in extract_images(html):
            blob = (img["src"] + " " + img["alt"]).lower()
            marker = next((mk for mk in AI_IMAGE_MARKERS if mk in blob), None)
            if not marker:
                continue
            window = html[max(0, img["start"] - 1500): img["end"] + 1500]
            disclosed = contains_any(
                extract_text(window), IMAGE_DISCLOSURE_PHRASES
            ) or contains_any(img["alt"], IMAGE_DISCLOSURE_PHRASES)
            if not disclosed:
                findings.append(
                    {
                        "id": "DC-003",
                        "severity": "MEDIUM",
                        "page": url,
                        "title": "AI-generated image without caption disclosure",
                        "evidence": "marker '%s' in %s"
                        % (marker, (img["alt"] or img["src"])[:120]),
                        "fix": (
                            "Label it visibly, e.g. 'AI-generated illustration' "
                            "in the caption or alt text — the EU AI Act requires "
                            "AI-generated content to be identifiable as such."
                        ),
                        "heuristic": True,
                    }
                )
    return findings


def check_ai_claims(pages):
    findings = []
    for page in pages:
        html, url = page["html"], page["url"]
        text = extract_text(html)
        claim = next((c for c in AI_CLAIM_PHRASES if c in text.lower()), None)
        if not claim:
            continue
        links = extract_links(html, url)
        has_disclosure_link = any(_is_policy_page(l) for l in links)
        if not has_disclosure_link:
            m = re.search(re.escape(claim), text, re.IGNORECASE)
            findings.append(
                {
                    "id": "DC-004",
                    "severity": "LOW",
                    "page": url,
                    "title": "'Powered by AI' claim with no linked disclosure page",
                    "evidence": evidence(text, m.start(), m.end()) if m else claim,
                    "fix": (
                        "Link the claim to your privacy/AI-disclosure page so "
                        "visitors can learn what 'AI' means on your site."
                    ),
                    "heuristic": True,
                }
            )
    return findings


def check_machine_readable(target):
    """Honest heuristic: look for disclosure.json or an AI section in llms.txt."""
    dj_url = urllib.parse.urljoin(target, "/disclosure.json")
    _, dj_body, dj_status = fetch(dj_url)
    if dj_body and dj_status == 200:
        try:
            data = json.loads(dj_body)
            blob = json.dumps(data).lower()
            if "ai" in blob and (
                "disclosure" in blob or "transparency" in blob or "generated" in blob
            ):
                return []
        except (json.JSONDecodeError, ValueError):
            pass
    llms_url = urllib.parse.urljoin(target, "/llms.txt")
    _, llms_body, llms_status = fetch(llms_url)
    if llms_body and llms_status == 200:
        low = llms_body.lower()
        if "ai" in low and (
            "disclosure" in low or "transparency" in low or "generated" in low
        ):
            return []
    return [
        {
            "id": "DC-005",
            "severity": "LOW",
            "page": target,
            "title": "No machine-readable AI disclosure found",
            "evidence": "no disclosure.json with AI content; no AI section in llms.txt",
            "fix": (
                "Publish /disclosure.json (or an AI section in llms.txt) "
                "stating which AI systems the site uses. This is an emerging "
                "best practice, not a settled legal requirement."
            ),
            "heuristic": True,
        }
    ]


